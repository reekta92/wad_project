CREATE TABLE departments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 100)
);
CREATE TABLE courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE CHECK (length(trim(code)) BETWEEN 1 AND 20),
    name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 100),
    kind text NOT NULL CHECK (kind IN ('mandatory', 'elective')),
    enrollment integer NOT NULL CHECK (enrollment > 0),
    term integer NOT NULL CHECK (term BETWEEN 1 AND 8),
    department_id bigint NOT NULL REFERENCES departments
);
CREATE TABLE classrooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 50),
    capacity integer NOT NULL CHECK (capacity > 0),
    type text NOT NULL CHECK (length(trim(type)) BETWEEN 1 AND 50),
    floor integer NOT NULL,
    active boolean NOT NULL DEFAULT true
);
CREATE TABLE sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    description text NOT NULL DEFAULT '',
    CHECK (start_time < end_time),
    UNIQUE (date, start_time)
);
CREATE TABLE personnel (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title text NOT NULL,
    first_name text NOT NULL CHECK (length(trim(first_name)) BETWEEN 1 AND 100),
    last_name text NOT NULL CHECK (length(trim(last_name)) BETWEEN 1 AND 100),
    department_id bigint NOT NULL REFERENCES departments
);
CREATE TABLE app_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer text NOT NULL,
    subject text NOT NULL,
    active boolean NOT NULL DEFAULT true,
    personnel_id bigint UNIQUE REFERENCES personnel,
    UNIQUE (issuer, subject)
);
CREATE TABLE unavailability_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    personnel_id bigint NOT NULL REFERENCES personnel,
    date date NOT NULL,
    session_id bigint REFERENCES sessions,
    type text NOT NULL CHECK (type IN ('leave', 'medical', 'advisory')),
    reason text NOT NULL CHECK (length(trim(reason)) BETWEEN 1 AND 500),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    decided_by bigint REFERENCES app_users,
    decided_at timestamptz,
    CHECK ((status = 'pending' AND decided_by IS NULL AND decided_at IS NULL)
        OR (status <> 'pending' AND decided_by IS NOT NULL AND decided_at IS NOT NULL))
);
CREATE TABLE exams (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL UNIQUE REFERENCES courses,
    session_id bigint NOT NULL REFERENCES sessions
);
CREATE TABLE exam_rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id bigint NOT NULL REFERENCES exams ON DELETE CASCADE,
    classroom_id bigint NOT NULL REFERENCES classrooms,
    UNIQUE (exam_id, classroom_id)
);
CREATE TABLE invigilator_assignments (
    id bigint PRIMARY KEY REFERENCES exam_rooms ON DELETE CASCADE,
    personnel_id bigint NOT NULL REFERENCES personnel
);
CREATE TABLE audit_logs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    actor_user_id bigint REFERENCES app_users,
    action text NOT NULL,
    entity text NOT NULL,
    entity_id bigint,
    old_value jsonb,
    new_value jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE schedule_state (
    id integer PRIMARY KEY CHECK (id = 1),
    published boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT now()
);
